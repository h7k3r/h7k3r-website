#!/usr/bin/env python3
"""Build reviews-data.js from the private h7k3r-reviews.json.

Usage:  python3 scripts/build_reviews.py /path/to/h7k3r-reviews.json

The source file is NOT committed (it holds customers' full names). Only public-safe
fields reach the site: first name + initial, year, star rating, category, the compiler's
summary (always shown labelled as a summary, never as a quote), the customer's exact
quote once H7K3R has filled it in, and the source label + link.

Rules followed (REVIEWS-README.md / DMCC Act 2024):
  - every usable review is included, in file order (no cherry-picking)
  - entries carrying a "verify" flag are held back until checked
  - no averages, percentages or counts are computed here
  - the owner's real name never appears
"""
import json, sys, os

src = sys.argv[1] if len(sys.argv) > 1 else "h7k3r-reviews.json"
d = json.load(open(src, encoding="utf-8"))

reviews = []
for r in d["reviews"]:
    if r.get("verify"):
        continue
    reviews.append({
        "id": r["id"],
        "n": r.get("display_name") or "Google reviewer",
        "y": (r.get("date") or "")[:4],
        "r": r.get("rating"),
        "c": r.get("category") or "general",
        "s": r.get("summary") or "",
        "src": r["source"],
        "q": (r.get("quote") or "").strip(),
        "f": bool(r.get("featured")),
        "lang": r.get("language") or "en",
    })

out = {
    "stats": d["headline_stats"]["safe_copy"],          # shown word for word
    "sources": {k: {"label": v["label"], "url": v["url"]} for k, v in d["sources"].items()},
    "ebay": {k: d["trust_badges"]["ebay"][k] for k in ("url", "member_since")},
    "reviews": reviews,
}
js = "/* Generated by scripts/build_reviews.py — do not edit by hand. */\nwindow.H7K_REVIEWS = " + \
     json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n"
here = os.path.dirname(os.path.abspath(__file__))
open(os.path.join(here, "..", "reviews-data.js"), "w", encoding="utf-8").write(js)
print("reviews-data.js: %d reviews (%d held back for verification), %d quotes filled"
      % (len(reviews), len(d["reviews"]) - len(reviews), sum(1 for x in reviews if x["q"])))
